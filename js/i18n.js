  const state = { lang: cfg.defaultLang };

  const dirOf = (lang) => (cfg.languages[lang] || cfg.languages.en).dir;
  const adminLang = () => (state.lang === "he" ? "he" : "en");

  function t(key, lang, vars) {
    if (lang && typeof lang === "object") { vars = lang; lang = null; }
    lang = lang || state.lang;
    let s = STR[lang] && STR[lang][key];
    if (s === undefined) s = STR.en[key];
    if (s === undefined) return key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
    return s;
  }

  const langFor = (el) => (el.closest('[data-i18n-scope="admin"]') ? adminLang() : state.lang);

  function apply(root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n, langFor(el)); });
    root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder, langFor(el)); });
    root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria, langFor(el))); });
    root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle, langFor(el)); });

    document.querySelectorAll('[data-i18n-scope="admin"]').forEach((el) => {
      el.lang = adminLang();
      el.dir = dirOf(adminLang());
    });
  }

  function setLang(lang, persist) {
    if (!cfg.languages[lang]) lang = cfg.defaultLang;
    state.lang = lang;
    const html = document.documentElement;
    html.lang = lang;
    html.dir = dirOf(lang);
    document.title = t("meta.title");
    const meta = document.querySelector('meta[name="description"]');
    if (meta) meta.content = t("meta.description");
    apply();
    if (persist !== false) DC.prefs.set({ lang });
    document.dispatchEvent(new CustomEvent("dc:langchange", { detail: { lang } }));
  }

  DC.i18n = {
    t, apply, setLang, dirOf, adminLang,
    get lang() { return state.lang; }
  };
