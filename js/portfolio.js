/* ==========================================================================
   DCreator – portfolio (link cards)
   · Data: published list (js/portfolio-data.js) + local edits made in Admin.
   · Rendering, category filter, auto-translation, image processing, export.
   ========================================================================== */
(function () {
  const cfg = DC.config;
  const KEY = cfg.keys.portfolio;
  const LANGS = Object.keys(cfg.languages);
  const CATS = ["web", "game", "sim", "other"];
  const CAT_ICON = { web: "i-web", game: "i-game", sim: "i-sim", other: "i-layout" };
  const SVG_NS = "http://www.w3.org/2000/svg";

  const clone = (o) => JSON.parse(JSON.stringify(o));
  const published = () => (Array.isArray(window.DC_PORTFOLIO_SEED) ? window.DC_PORTFOLIO_SEED : []);

  let items = [];
  let filter = "all";
  let observer = null;

  /* ---------------------------------------------------------------- data */
  function load() {
    const saved = DC.store.read(KEY, null);
    items = Array.isArray(saved) ? saved : clone(published());
  }

  function emitChange() { document.dispatchEvent(new CustomEvent("dc:portfoliochange")); }

  function persist() { return DC.store.write(KEY, items); }

  function upsert(item) {
    const before = clone(items);
    const i = items.findIndex((it) => it.id === item.id);
    if (i >= 0) items[i] = item; else items.unshift(item);
    if (!persist()) { items = before; return false; }
    emitChange();
    return true;
  }

  function remove(id) {
    const before = clone(items);
    items = items.filter((it) => it.id !== id);
    if (!persist()) { items = before; return false; }
    emitChange();
    return true;
  }

  /* clean   = same as the live file
     pending = already sent to GitHub, the site is still rebuilding
     dirty   = local changes that are not published anywhere yet */
  function publishState() {
    const now = JSON.stringify(items);
    if (now === JSON.stringify(published())) return "clean";
    return now === DC.store.read(cfg.keys.lastPublished, null) ? "pending" : "dirty";
  }

  const snapshot = () => JSON.stringify(items);
  const markPublished = (sent) => DC.store.write(cfg.keys.lastPublished, sent || snapshot());

  function resetLocal() {
    DC.store.remove(KEY);
    DC.store.remove(cfg.keys.lastPublished);
    items = clone(published());
    emitChange();
  }

  function exportJs() {
    const stamp = new Date().toISOString().slice(0, 10);
    return "/* Generated by the DCreator admin panel on " + stamp + ".\n" +
      "   Replace js/portfolio-data.js on your hosting with this file. */\n" +
      "window.DC_PORTFOLIO_SEED = " + JSON.stringify(items, null, 2) + ";\n";
  }

  const newId = () => "p_" + Date.now().toString(36) + Math.random().toString(36).slice(2, 6);

  /* ------------------------------------------------------------- helpers */
  /* Only http(s) links are ever used – blocks javascript: / data: URLs. */
  function safeUrl(raw) {
    raw = String(raw || "").trim();
    if (!raw) return "";
    if (!/^[a-z][a-z0-9+.-]*:/i.test(raw)) raw = "https://" + raw;
    try {
      const u = new URL(raw);
      return (u.protocol === "http:" || u.protocol === "https:") && u.hostname.includes(".") ? u.href : "";
    } catch (e) { return ""; }
  }

  const isImageSrc = (s) => /^data:image\//i.test(s) || !!safeUrl(s) && /^https?:/i.test(s);

  function hostOf(url) {
    try { return new URL(url).hostname.replace(/^www\./, ""); } catch (e) { return ""; }
  }

  function pick(map, lang, srcLang) {
    if (!map) return "";
    return map[lang] || map[srcLang] || map.en || Object.values(map).find(Boolean) || "";
  }

  function svgIcon(id) {
    const svg = document.createElementNS(SVG_NS, "svg");
    svg.setAttribute("class", "icon");
    svg.setAttribute("aria-hidden", "true");
    const use = document.createElementNS(SVG_NS, "use");
    use.setAttribute("href", "#" + id);
    svg.appendChild(use);
    return svg;
  }

  function el(tag, className, text) {
    const node = document.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined) node.textContent = text;
    return node;
  }

  /* Gradient placeholder used when a project has no (working) image. */
  function thumbFallback(item) {
    const box = el("div", "thumb-fallback");
    box.dataset.cat = item.category;
    box.appendChild(svgIcon(CAT_ICON[item.category] || "i-web"));
    box.appendChild(el("span", "", hostOf(item.url)));
    return box;
  }

  function thumb(item) {
    if (item.image && isImageSrc(item.image)) {
      const img = new Image();
      img.alt = "";
      img.loading = "lazy";
      img.decoding = "async";
      img.referrerPolicy = "no-referrer";
      img.src = item.image;
      img.addEventListener("error", () => img.replaceWith(thumbFallback(item)), { once: true });
      return img;
    }
    return thumbFallback(item);
  }

  /* ----------------------------------------------------------- rendering */
  function buildCard(item, lang) {
    const href = safeUrl(item.url);
    const card = el("a", "card glass reveal");
    card.href = href;
    card.target = "_blank";
    card.rel = "noopener noreferrer";

    const media = el("div", "card-media");
    media.appendChild(thumb(item));
    media.appendChild(el("span", "badge", DC.i18n.t("filter." + item.category)));
    card.appendChild(media);

    const body = el("div", "card-body");
    body.appendChild(el("h3", "", pick(item.title, lang, item.srcLang)));
    const desc = pick(item.desc, lang, item.srcLang);
    if (desc) body.appendChild(el("p", "", desc));
    const foot = el("div", "card-foot");
    foot.appendChild(el("span", "host", hostOf(href)));
    const visit = el("span", "visit");
    visit.appendChild(el("span", "", DC.i18n.t("portfolio.visit")));
    visit.appendChild(svgIcon("i-link"));
    foot.appendChild(visit);
    body.appendChild(foot);
    card.appendChild(body);
    return card;
  }

  function reveal(cards) {
    if (!("IntersectionObserver" in window)) { cards.forEach((c) => c.classList.add("in")); return; }
    if (!observer) {
      observer = new IntersectionObserver((entries) => {
        entries.forEach((en) => {
          if (en.isIntersecting) { en.target.classList.add("in"); observer.unobserve(en.target); }
        });
      }, { threshold: 0.12 });
    }
    cards.forEach((c, i) => { c.style.transitionDelay = Math.min(i * 60, 360) + "ms"; observer.observe(c); });
  }

  function render() {
    const grid = document.getElementById("portfolio-grid");
    const empty = document.getElementById("portfolio-empty");
    if (!grid) return;
    const lang = DC.i18n.lang;
    const list = items.filter((it) => safeUrl(it.url) && (filter === "all" || it.category === filter));
    grid.textContent = "";
    const cards = list.map((it) => buildCard(it, lang));
    cards.forEach((c) => grid.appendChild(c));
    empty.hidden = list.length > 0;
    reveal(cards);
  }

  function setFilter(value) {
    filter = CATS.includes(value) ? value : "all";
    document.querySelectorAll("#portfolio-filters [data-filter]").forEach((b) => {
      const on = b.dataset.filter === filter;
      b.classList.toggle("is-active", on);
      b.setAttribute("aria-pressed", String(on));
    });
    render();
  }

  function initFilters() {
    const bar = document.getElementById("portfolio-filters");
    if (!bar) return;
    bar.addEventListener("click", (e) => {
      const btn = e.target.closest("[data-filter]");
      if (btn) setFilter(btn.dataset.filter);
    });
  }

  /* The portfolio starts closed and opens on click. */
  function syncToggle() {
    const btn = document.getElementById("portfolio-toggle");
    const panel = document.getElementById("portfolio-panel");
    if (!btn || !panel) return;
    const label = btn.querySelector("span");
    const open = !panel.hidden;
    btn.setAttribute("aria-expanded", String(open));
    label.dataset.i18n = open ? "portfolio.close" : "portfolio.open";
    label.textContent = DC.i18n.t(label.dataset.i18n);
  }

  function initToggle() {
    const btn = document.getElementById("portfolio-toggle");
    const panel = document.getElementById("portfolio-panel");
    if (!btn || !panel) return;
    btn.addEventListener("click", () => { panel.hidden = !panel.hidden; syncToggle(); });
    document.addEventListener("dc:langchange", syncToggle);
  }

  /* Opens the portfolio (optionally on one category) and scrolls to it. */
  function show(category) {
    const panel = document.getElementById("portfolio-panel");
    if (!panel) return;
    panel.hidden = false;
    syncToggle();
    setFilter(category || "all");
    document.getElementById("portfolio").scrollIntoView();
  }

  /* ---------------------------------------------------------- translation */
  const encoder = new TextEncoder();
  const byteLen = (s) => encoder.encode(s).length;
  const decodeEntities = (s) => new DOMParser().parseFromString(s, "text/html").documentElement.textContent;

  function hardSplit(s, max) {
    const parts = [];
    while (s) {
      let n = Math.min(s.length, max);
      while (n > 1 && byteLen(s.slice(0, n)) > max) n--;
      let cut = n;
      if (n < s.length) { const sp = s.lastIndexOf(" ", n); if (sp > n * 0.4) cut = sp; }
      parts.push(s.slice(0, cut));
      s = s.slice(cut).trimStart();
    }
    return parts;
  }

  /* The free API accepts ~500 bytes per request, so long text goes in chunks. */
  function chunk(text, max) {
    const sentences = text.match(/[^.!?。！？\n]+[.!?。！？]*\s*/g) || [text];
    const pieces = [];
    sentences.forEach((s) => (byteLen(s) > max ? pieces.push(...hardSplit(s, max)) : pieces.push(s)));
    const out = [];
    let cur = "";
    pieces.forEach((p) => {
      if (cur && byteLen(cur + p) > max) { out.push(cur.trim()); cur = ""; }
      cur += p;
    });
    if (cur.trim()) out.push(cur.trim());
    return out;
  }

  async function translateChunk(text, from, to) {
    const tr = cfg.translation;
    const pair = cfg.languages[from].mm + "|" + cfg.languages[to].mm;
    const url = tr.endpoint + "?q=" + encodeURIComponent(text) + "&langpair=" + encodeURIComponent(pair);
    const ctrl = new AbortController();
    const timer = setTimeout(() => ctrl.abort(), 12000);
    try {
      const res = await fetch(url, { signal: ctrl.signal });
      if (!res.ok) throw new Error("HTTP " + res.status);
      const json = await res.json();
      const out = json && json.responseData && json.responseData.translatedText;
      if (!out || Number(json.responseStatus) !== 200 || /MYMEMORY WARNING|INVALID LANGUAGE/i.test(out)) {
        throw new Error("Translation service refused the request");
      }
      return decodeEntities(out);
    } finally { clearTimeout(timer); }
  }

  async function translateText(text, from, to) {
    if (!text || from === to) return text;
    const parts = [];
    for (const c of chunk(text, cfg.translation.maxBytesPerRequest)) parts.push(await translateChunk(c, from, to));
    return parts.join(" ");
  }

  /* Translates title + description into every other language.
     Languages that fail fall back to the original text and are reported. */
  async function translateAll(source, from, onProgress) {
    const targets = LANGS.filter((l) => l !== from);
    const result = { title: {}, desc: {}, failed: [] };
    let done = 0;
    for (const lang of targets) {
      try {
        const [title, desc] = await Promise.all([
          translateText(source.title, from, lang),
          translateText(source.desc, from, lang)
        ]);
        result.title[lang] = title;
        result.desc[lang] = desc;
      } catch (e) {
        result.title[lang] = source.title;
        result.desc[lang] = source.desc;
        result.failed.push(lang);
      }
      done += 1;
      if (onProgress) onProgress(done, targets.length);
    }
    return result;
  }

  /* ---------------------------------------------------------------- image */
  function processImageFile(file) {
    return new Promise((resolve, reject) => {
      if (!file || !/^image\//.test(file.type)) { reject(new Error("image")); return; }
      if (file.size > 8 * 1024 * 1024) { reject(new Error("size")); return; }
      const url = URL.createObjectURL(file);
      const img = new Image();
      img.onload = () => {
        const nw = img.naturalWidth || 400, nh = img.naturalHeight || 250;
        const scale = Math.min(1, 800 / Math.max(nw, nh));
        const c = document.createElement("canvas");
        c.width = Math.max(1, Math.round(nw * scale));
        c.height = Math.max(1, Math.round(nh * scale));
        c.getContext("2d").drawImage(img, 0, 0, c.width, c.height);
        URL.revokeObjectURL(url);
        let out = c.toDataURL("image/webp", 0.85);
        if (!out.startsWith("data:image/webp")) out = c.toDataURL("image/png");
        resolve(out);
      };
      img.onerror = () => { URL.revokeObjectURL(url); reject(new Error("image")); };
      img.src = url;
    });
  }

  /* ----------------------------------------------------------------- init */
  function init() {
    load();
    initFilters();
    initToggle();
    render();
    document.addEventListener("dc:langchange", render);
    document.addEventListener("dc:portfoliochange", render);
  }

  DC.portfolio = {
    init, render, LANGS, CATS,
    all: () => items,
    byId: (id) => items.find((it) => it.id === id),
    upsert, remove, publishState, markPublished, snapshot, resetLocal, exportJs, newId, show,
    safeUrl, hostOf, pick, isImageSrc, thumbFallback,
    translateAll, processImageFile
  };
})();
